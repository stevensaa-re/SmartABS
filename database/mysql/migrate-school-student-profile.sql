USE smartabs;

CREATE TABLE IF NOT EXISTS school_profile (
  id               TINYINT UNSIGNED NOT NULL DEFAULT 1,
  name             VARCHAR(160) NOT NULL DEFAULT '',
  address          VARCHAR(500) NOT NULL DEFAULT '',
  phone            VARCHAR(40) NOT NULL DEFAULT '',
  education_levels TEXT NOT NULL,
  majors           TEXT NOT NULL,
  updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

ALTER TABLE classes
  ADD COLUMN education_level VARCHAR(10) NOT NULL DEFAULT 'SMA' AFTER name;

ALTER TABLE students
  ADD COLUMN nisn CHAR(10) NULL AFTER name,
  ADD COLUMN birth_place VARCHAR(100) NOT NULL DEFAULT '',
  ADD COLUMN birth_date DATE NULL,
  ADD COLUMN address VARCHAR(500) NOT NULL DEFAULT '',
  ADD COLUMN father_name VARCHAR(100) NOT NULL DEFAULT '',
  ADD COLUMN mother_name VARCHAR(100) NOT NULL DEFAULT '',
  ADD COLUMN guardian_name VARCHAR(100) NOT NULL DEFAULT '',
  ADD UNIQUE KEY uq_students_nisn (nisn);
